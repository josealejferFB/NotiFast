/**
 * NotiFast 3.0 Tactical Agenda Creation Action Selector.
 */
@Composable
fun AgendaCreateActionBottomSheet(
    onAddSchedule: () -> Unit,
    onAddEvaluation: () -> Unit,
    modifier: Modifier = Modifier
) {
    Column(
        modifier = modifier
            .fillMaxWidth()
            .padding(horizontal = 24.dp, vertical = 8.dp)
            .padding(bottom = 36.dp)
    ) {
        Text(
            text = stringResource(R.string.agenda_create_title),
            style = MaterialTheme.typography.titleMedium,
            fontWeight = FontWeight.Bold,
            color = MaterialTheme.colorScheme.onSurface
        )

        Spacer(modifier = Modifier.height(16.dp))

        ActionCard(
            title = stringResource(R.string.agenda_create_schedule_option),
            description = stringResource(R.string.agenda_create_schedule_desc),
            icon = Icons.Default.Schedule,
            iconTint = MaterialTheme.colorScheme.primary,
            iconBg = MaterialTheme.colorScheme.primaryContainer.copy(alpha = 0.5f),
            onClick = onAddSchedule
        )

        Spacer(modifier = Modifier.height(12.dp))

        ActionCard(
            title = stringResource(R.string.agenda_create_evaluation_option),
            description = stringResource(R.string.agenda_create_evaluation_desc),
            icon = Icons.AutoMirrored.Filled.Assignment,
            iconTint = MaterialTheme.colorScheme.error,
            iconBg = MaterialTheme.colorScheme.errorContainer.copy(alpha = 0.5f),
            onClick = onAddEvaluation
        )
    }
}

@Composable
private fun ActionCard(
    title: String,
    description: String,
    icon: ImageVector,
    iconTint: Color,
    iconBg: Color,
    onClick: () -> Unit
) {
    Card(
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        border = BorderStroke(1.dp, MaterialTheme.colorScheme.outlineVariant),
        elevation = CardDefaults.cardElevation(defaultElevation = 0.dp),
        modifier = Modifier
            .fillMaxWidth()
            .clip(RoundedCornerShape(16.dp))
            .clickable(
                interactionSource = remember { MutableInteractionSource() },
                indication = null,
                onClick = onClick
            )
    ) {
        Row(
            modifier = Modifier.padding(16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Box(
                modifier = Modifier
                    .size(48.dp)
                    .clip(CircleShape)
                    .background(iconBg),
                contentAlignment = Alignment.Center
            ) {
                Icon(
                    imageVector = icon,
                    contentDescription = null,
                    tint = iconTint,
                    modifier = Modifier.size(24.dp)
                )
            }

            Spacer(modifier = Modifier.width(14.dp))

            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = title,
                    fontWeight = FontWeight.Bold,
                    fontSize = 15.sp,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Spacer(modifier = Modifier.height(2.dp))
                Text(
                    text = description,
                    fontSize = 12.sp,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    lineHeight = 16.sp
                )
            }
        }
    }
}
