@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SettingsThemeDialog(
    currentTheme: Boolean?,
    onSelectTheme: (Boolean?) -> Unit,
    onDismiss: () -> Unit
) {
    BasicAlertDialog(
        onDismissRequest = onDismiss
    ) {
        Surface(
            shape = RoundedCornerShape(24.dp),
            color = MaterialTheme.colorScheme.surface,
            border = BorderStroke(1.dp, MaterialTheme.colorScheme.outlineVariant),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(24.dp)
            ) {
                Text(
                    text = stringResource(R.string.settings_appearance_theme_title),
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onSurface
                )

                Spacer(modifier = Modifier.height(16.dp))

                ThemeOptionItem(
                    title = stringResource(R.string.settings_appearance_theme_system),
                    subtitle = stringResource(R.string.settings_appearance_theme_system_desc),
                    icon = Icons.Default.BrightnessAuto,
                    isSelected = currentTheme == null,
                    onClick = {
                        onSelectTheme(null)
                        onDismiss()
                    }
                )

                ThemeOptionItem(
                    title = stringResource(R.string.settings_appearance_theme_light),
                    subtitle = stringResource(R.string.settings_appearance_theme_light_desc),
                    icon = Icons.Default.LightMode,
                    isSelected = currentTheme == false,
                    onClick = {
                        onSelectTheme(false)
                        onDismiss()
                    }
                )

                ThemeOptionItem(
                    title = stringResource(R.string.settings_appearance_theme_dark),
                    subtitle = stringResource(R.string.settings_appearance_theme_dark_desc),
                    icon = Icons.Default.DarkMode,
                    isSelected = currentTheme == true,
                    onClick = {
                        onSelectTheme(true)
                        onDismiss()
                    }
                )
            }
        }
    }
}

@Composable
private fun ThemeOptionItem(
    title: String,
    subtitle: String,
    icon: ImageVector,
    isSelected: Boolean,
    onClick: () -> Unit
) {
    Surface(
        onClick = onClick,
        modifier = Modifier
            .fillMaxWidth()
            .padding(vertical = 4.dp),
        shape = RoundedCornerShape(14.dp),
        color = if (isSelected) MaterialTheme.colorScheme.primaryContainer.copy(alpha = 0.4f)
        else MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.3f),
        border = BorderStroke(
            1.dp,
            if (isSelected) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.outlineVariant
        )
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(12.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Icon(
                imageVector = icon,
                contentDescription = null,
                tint = if (isSelected) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.size(22.dp)
            )

            Spacer(modifier = Modifier.width(12.dp))

            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = title,
                    style = MaterialTheme.typography.bodyMedium,
                    fontWeight = FontWeight.SemiBold,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Text(
                    text = subtitle,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }

            RadioButton(
                selected = isSelected,
                onClick = onClick,
                colors = RadioButtonDefaults.colors(
                    selectedColor = MaterialTheme.colorScheme.primary
                )
            )
        }
    }
}
